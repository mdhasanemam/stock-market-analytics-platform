"""Reproducible benchmark: walk-forward comparison of all models vs baselines on the bundled sample data.

    DATA_PROVIDER=csv python scripts/benchmark.py            # writes docs/BENCHMARK.md
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

os.environ.setdefault("DATA_PROVIDER", "csv")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from backend.app.core.config import get_settings  # noqa: E402
from backend.app.services.data_service import DataService  # noqa: E402
from backend.app.services.prediction_service import PredictionService  # noqa: E402
from backend.app.services.providers import get_provider  # noqa: E402
from backend.ml.models import MODELS  # noqa: E402

SYMBOLS, HORIZON, PERIOD = ["AAPL", "FB", "MSFT", "TSLA"], 5, "10Y"


def main() -> None:
    s = get_settings()
    ps = PredictionService(DataService(get_provider(s), s), s)
    lines = [f"# Benchmark (generated by `scripts/benchmark.py`)\n",
             f"Provider: `{s.data_provider}` (bundled sample, data ends 2017-11-10) · horizon: {HORIZON} trading days · history: {PERIOD} · "
             f"walk-forward, refit every {s.ml_refit_every} days, up to {s.ml_max_test_days} out-of-sample forecasts.\n",
             "MAE is in price units, so compare models **within** a ticker, not across tickers. "
             "`vs persist.` / `vs drift` = MAE reduction relative to those baselines (positive = better). "
             "A model has demonstrated edge only if it clearly beats both.\n"]
    for sym in SYMBOLS:
        t0 = time.time()
        r = ps.compare(sym, list(MODELS), HORIZON, PERIOD)
        lines += [f"## {sym}  ({r['n_test_points']} out-of-sample forecasts, {time.time() - t0:.0f}s)\n",
                  "| Rank | Model | MAE | RMSE | R² (price) | Dir. acc. | vs persist. | vs drift | Edge? |", "|---|---|---|---|---|---|---|---|---|"]
        for i, row in enumerate(r["leaderboard"], 1):
            m = row["metrics"]
            da = "—" if m["directional_accuracy"] is None else f"{m['directional_accuracy'] * 100:.1f}%"
            edge = "baseline" if row["kind"] == "baseline" else ("yes" if row["beats_all_baselines"] else "no")
            lines.append(f"| {i} | {row['label']} | {m['mae']:.3f} | {m['rmse']:.3f} | {m['r2']:.4f} | {da} | "
                         f"{m['mae_improvement_vs_persistence'] * 100:+.1f}% | {m['mae_improvement_vs_drift'] * 100:+.1f}% | {edge} |")
        lines += ["", f"_{r['summary']}_", ""]
        print(f"{sym}: {r['summary']}", flush=True)
    out = Path(__file__).resolve().parents[1] / "docs" / "BENCHMARK.md"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
